#!/usr/bin/env bash
# gen_env.sh — Generate .env for docker compose from the known deployment values.
# Run once before first build: bash gen_env.sh
# Re-run if the Windows host IP changes (WSL network reassignment).

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="$SCRIPT_DIR/.env"

# ── Windows host IP (Dahua VMS lives on the Windows host) ──────────────────────
WINDOWS_HOST=$(ip route show | awk '/^default/ {print $3; exit}')
if [ -z "$WINDOWS_HOST" ]; then
    echo "ERROR: could not detect Windows host IP via default route" >&2
    exit 1
fi
echo "  Windows host IP: $WINDOWS_HOST"

cat > "$ENV_FILE" << EOF
# Generated by gen_env.sh — do NOT commit this file.
# Re-run gen_env.sh if the Windows host IP changes.

# ── Cameras ──
CHANNELS=4 1
RTSP_CAMERAS=hik1=rtsp://admin:Waycon2025@10.0.0.78:554/Streaming/Channels/101

# ── Dahua VMS (frames) ──
VMS_URL=http://${WINDOWS_HOST}:5057
VMS_DEVICE_IP=192.168.40.200
VMS_DEVICE_PORT=37777
VMS_USERNAME=admin
VMS_PASSWORD=broNO_WoRk-2026
VMS_CHANNEL_OFFSET=-1

# ── OpenRouter (review agent) — agent self-disables if key absent ──
OPENROUTER_API_KEY=
YOUR_SITE_URL=http://localhost
YOUR_SITE_NAME=vehicle_services

# ── Sprint H training-data collector ──
DATASET_COLLECT_ENABLED=true
DATASET_INTERVAL_SEC=5.0
DATASET_JPEG_QUALITY=85

# ── optional tunables ──
COLOR_FEATURE_MODE=hsv
STREAM_TYPE=0
DISPLAY_FPS=15
SEND_LOWCONF_ONLY=0
EOF

echo "  Written: $ENV_FILE"
echo "  (Set OPENROUTER_API_KEY in .env if you want the review agent enabled.)"
